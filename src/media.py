def sha(path):
    h=hashlib.sha256()
    with Path(path).open('rb') as f:
        for c in iter(lambda:f.read(4*1024*1024),b''): h.update(c)
    return h.hexdigest()

def write_json(path, obj):
    Path(path).parent.mkdir(parents=True, exist_ok=True)
    Path(path).write_text(json.dumps(obj, indent=2, ensure_ascii=False, allow_nan=False, default=str),encoding='utf-8')

def clean(value):
    return re.sub(r'\s+',' ',html.unescape(re.sub('<[^>]+>',' ',str(value or '')))).strip()

def fetch(url, params, provider):
    key=hashlib.sha256((url+json.dumps(params,sort_keys=True)).encode()).hexdigest()
    path=RAW/provider/(key+'.raw')
    meta_path=path.with_suffix('.metadata.json')
    path.parent.mkdir(parents=True,exist_ok=True)
    if path.exists() and meta_path.exists():
        meta=json.loads(meta_path.read_text(encoding='utf-8'))
        if sha(path)!=meta['sha256']: raise ValueError('Raw response hash mismatch')
        if meta['http_status']==200: return path.read_bytes(), meta
    body=b''; status=0; errors=[]; resolved=''
    for attempt in range(3):
        try:
            response=requests.get(url,params=params,timeout=(15,40),headers={'User-Agent':'Academic economic narrative measurement/1.0'})
            body=response.content; status=response.status_code; resolved=response.url
            if status==200: break
            errors.append(f'HTTP {status}')
        except requests.RequestException as exc: errors.append(str(exc))
        time.sleep(1+attempt)
    path.write_bytes(body)
    meta={'request_url':resolved or url,'params':params,'http_status':status,
          'retrieved_at':datetime.now(timezone.utc).isoformat(),'sha256':sha(path),
          'raw_path':path.relative_to(ROOT).as_posix(),'bytes':len(body),'errors':errors}
    write_json(meta_path,meta)
    return body,meta

def news_job(start, stop, panel):
    source,domain,group,geography=panel
    query=f'site:{domain} {QUERY} after:{start:%Y-%m-%d} before:{stop:%Y-%m-%d}'
    body,meta=fetch('https://news.google.com/rss/search',{'q':query,'hl':'en-US','gl':'US','ceid':'US:en'},'google_news')
    audit=dict(meta,provider='Google News RSS',source=source,source_group=group,month=f'{start:%Y-%m-01}',returned=0,capped=False)
    records=[]
    if meta['http_status']==200:
        try:
            items=ET.fromstring(body).findall('./channel/item'); audit.update(returned=len(items),capped=len(items)>=100)
            for item in items:
                title=clean(item.findtext('title')); feed_source=clean(item.findtext('source'))
                if feed_source and title.endswith(' - '+feed_source): title=title[:-len(feed_source)-3]
                source_el=item.find('source'); source_url=source_el.attrib.get('url','') if source_el is not None else ''
                try: stamp=parsedate_to_datetime(item.findtext('pubDate')).astimezone(timezone.utc).isoformat()
                except (ValueError,TypeError): stamp=''
                link=item.findtext('link') or ''
                records.append({'id':'gn_'+hashlib.sha256(link.encode()).hexdigest()[:24], 'source':source,
                  'source_group':group,'geography':geography,'feed_source':feed_source,'source_url':source_url,
                  'source_domain':domain,'published_at':stamp,'query_month':f'{start:%Y-%m-01}',
                  'text':title,'url':link,'record_kind':'headline','query':query,'points':None,'num_comments':None,
                  'author_hash':'','query_start':str(start.date()),'query_stop':str(stop.date()),**meta})
        except ET.ParseError as exc: audit['parse_error']=str(exc)
    return records,[audit]

def social_job(start,stop,term):
    left=int(start.tz_localize('America/New_York').timestamp()); right=int(stop.tz_localize('America/New_York').timestamp())
    def shard(a,b):
        body,meta=fetch('https://hn.algolia.com/api/v1/search_by_date',
            {'query':term,'tags':'story','numericFilters':f'created_at_i>={a},created_at_i<{b}',
             'hitsPerPage':1000,'page':0,'typoTolerance':'false','queryType':'prefixNone'},'hn_algolia')
        audit=dict(meta,provider='HN Algolia',source='Hacker News',source_group='social',month=f'{start:%Y-%m-01}',returned=0,capped=False,used_as_leaf=True)
        if meta['http_status']!=200:return [],[audit]
        try: obj=json.loads(body)
        except ValueError as exc:audit['parse_error']=str(exc);return [],[audit]
        hits=obj.get('hits',[]);audit.update(returned=len(hits),reported_hits=obj.get('nbHits'),exhaustive=obj.get('exhaustiveNbHits'))
        if obj.get('nbHits',0)>len(hits) or len(hits)>=1000:
            audit.update(capped=True,used_as_leaf=False)
            if b-a<2:raise ValueError('Unresolvable HN hit cap')
            mid=(a+b)//2; r1,a1=shard(a,mid);r2,a2=shard(mid,b);return r1+r2,[audit]+a1+a2
        records=[]
        for hit in hits:
            ident=str(hit['objectID']); author=hit.get('author','') or ''
            records.append({'id':'hn_'+ident,'source':'Hacker News','source_group':'social',
             'geography':'US relevance uncertain; global technology-oriented platform','feed_source':'Hacker News',
             'source_url':hit.get('url',''),'source_domain':'news.ycombinator.com','published_at':hit.get('created_at',''),
             'query_month':f'{start:%Y-%m-01}','text':clean(hit.get('title')),'url':'https://news.ycombinator.com/item?id='+ident,
             'record_kind':'social_story_title','query':term,'points':hit.get('points'),'num_comments':hit.get('num_comments'),
             'author_hash':hashlib.sha256(author.encode()).hexdigest()[:16] if author else '',
             'query_start':str(start.date()),'query_stop':str(stop.date()),**meta})
        return records,[audit]
    return shard(left,right)

def acquire(start='2020-01-01',end='2026-10-13',workers=10,per_source=12):
    for d in [RAW,DATA,OUT]:d.mkdir(parents=True,exist_ok=True)
    start=pd.Timestamp(start);end=pd.Timestamp(end)
    jobs=[]
    for month in pd.date_range(start,end,freq='MS'):
        stop=min(month+pd.offsets.MonthBegin(1),end)
        if stop<=month:continue
        jobs.extend(('news',(month,stop,panel)) for panel in PANEL)
        jobs.extend(('social',(month,stop,term)) for term in HN_TERMS)
    records=[];audits=[]
    with ThreadPoolExecutor(max_workers=workers) as pool:
        fs={pool.submit(news_job if kind=='news' else social_job,*args):(kind,args) for kind,args in jobs}
        for i,f in enumerate(as_completed(fs)):
            try:r,a=f.result();records+=r;audits+=a
            except Exception as exc:audits.append({'job':str(fs[f]),'exception':str(exc)})
            if (i+1)%60==0 or i+1==len(fs):print(f'Acquired {i+1}/{len(fs)} request jobs; {len(records):,} candidate rows',flush=True)
    write_json(OUT/'media_request_audit.json',audits)
    frame=pd.DataFrame(records)
    if frame.empty:raise ValueError('No corpus records acquired')
    frame['published_at']=pd.to_datetime(frame.published_at,utc=True,errors='coerce')
    local=frame.published_at.dt.tz_convert('America/New_York')
    frame['available_at']=((local.dt.tz_localize(None).dt.normalize()+pd.Timedelta(days=1)).dt.tz_localize('America/New_York').dt.tz_convert('UTC')).astype(str)
    frame.loc[frame.source_group.eq('social'),'available_at']=frame.loc[frame.source_group.eq('social'),'published_at'].astype(str)
    frame['publication_precision']=np.where(frame.source_group.eq('social'),'HN creation timestamp; title edits not archived','RSS publisher date; repeated default hours, intraday precision unverified')
    frame['month']=local.dt.tz_localize(None).dt.to_period('M').dt.to_timestamp().astype(str)
    frame['normalized_title']=frame.text.str.lower().map(lambda s:re.sub(r'[^a-z0-9]+',' ',s).strip())
    frame['geographic_relevance']=frame.text.map(lambda t:'explicit_us' if US.search(t) else 'explicit_foreign_only' if FOREIGN.search(t) else 'not_stated')
    frame['exclusion_reason']=''
    frame.loc[frame.text.str.len().lt(8),'exclusion_reason']='empty_or_short'
    frame.loc[~frame.text.str.contains(ECON),'exclusion_reason']='no_title_economic_term'
    frame.loc[frame.geographic_relevance.eq('explicit_foreign_only'),'exclusion_reason']='explicit_foreign_without_us'
    frame.loc[frame.text.str.contains(r'\b(sponsored|advertisement|promo code|discount code)\b',case=False,regex=True),'exclusion_reason']='advertising_proxy'
    outside=local.dt.tz_localize(None).lt(start)|local.dt.tz_localize(None).ge(end)|frame.published_at.isna()
    frame.loc[outside,'exclusion_reason']='out_of_cutoff_or_missing_date'
    # Source-domain verification prevents syndicated copies from entering a named publisher stratum.
    mismatch=frame.source_group.ne('social') & ~frame.apply(lambda r:urlparse(str(r.source_url)).hostname in [r.source_domain,'www.'+r.source_domain],axis=1)
    frame.loc[mismatch,'exclusion_reason']='publisher_domain_mismatch'
    frame=frame.sort_values(['published_at','id','query'])
    duplicate=frame.duplicated('id',keep='first')
    frame.loc[duplicate,'exclusion_reason']='duplicate_id'
    eligible=frame.exclusion_reason.eq('')
    near=frame.loc[eligible].duplicated(['source','normalized_title'],keep='first')
    frame.loc[near[near].index,'exclusion_reason']='duplicate_title_within_source'
    frame['title_cluster']=frame.normalized_title.map(lambda t:hashlib.sha256(t.encode()).hexdigest()[:16])
    frame['repost_cluster_size']=frame.groupby('title_cluster').id.transform('nunique')
    frame['sampling_hash']=frame.id.map(lambda i:hashlib.sha256(f'{SEED}:{i}'.encode()).hexdigest())
    eligible=frame.exclusion_reason.eq('')
    chosen=frame.loc[eligible].sort_values('sampling_hash').groupby(['source','month'],sort=True).head(per_source).index
    frame['sampled']=frame.index.isin(chosen)
    frame['suspected_automation']='unassessed'
    social=frame.source_group.eq('social')
    counts=frame.loc[social&eligible].groupby(['author_hash','month']).id.transform('nunique')
    frame.loc[counts[counts>=15].index,'suspected_automation']='high_activity_author_proxy_not_bot_diagnosis'
    frame.to_csv(DATA/'media_candidates.csv',index=False)
    corpus=frame.loc[chosen].sort_values(['month','source','id']).copy()
    corpus.to_csv(DATA/'media_corpus.csv',index=False)
    write_json(OUT/'media_acquisition.json',{'start':str(start.date()),'cutoff_exclusive_ny':str(end.date()),
      'candidate_rows':len(frame),'eligible_unique':int(eligible.sum()),'sampled':len(corpus),
      'source_month_cap':per_source,'seed':SEED,'request_jobs':len(jobs),'request_records':len(audits),
      'failed_requests':sum(a.get('http_status',0)!=200 for a in audits),'capped_news_queries':sum(a.get('capped',False) and a.get('provider')=='Google News RSS' for a in audits),
      'exclusions':frame.exclusion_reason.value_counts().to_dict(),'corpus_sha256':sha(DATA/'media_corpus.csv'),
      'codebook_sha256':sha(ROOT/'docs/MEDIA_CODEBOOK.md'),'balanced_panel':PANEL,
      'availability':'Retrospective publisher timestamps; historical Google index membership and original HN title vintages unavailable',
      'raw_responses':'Cached byte-for-byte; hashes checked on reuse','query':QUERY,'hn_terms':HN_TERMS})
    print(f'Saved {len(corpus):,} titles in {corpus.month.nunique()} months',flush=True)
    return screen_corpus()

def strict_screen_reason(text):
    # Deterministic title-level repairs prompted by annotation-pool inspection.
    # These rules are development screening; they are never described as untouched holdout validation.
    word_sense_text=re.sub(r'\bgood job(?= market\b)','',text,flags=re.I)
    if OFF_TOPIC.search(word_sense_text):return 'clear_non_economic_word_sense_or_entertainment'
    if UNRELATED_JOB.search(text) and re.search(r'\bjobs?\b',text,re.I) and not ECON_WITHOUT_GENERIC_JOB.search(text) and not re.search(r'\btuition\b',text,re.I):
        return 'individual_political_sports_or_court_job_without_economic_context'
    text_us=re.sub(r'\b(?:South|Latin) American\w*\b','',text,flags=re.I)
    # Georgia is also a US state, Puerto Rico is a US territory, Jordan can be a personal name.
    foreign_text=re.sub(r'\b(Georgia\w*|Puerto Rico|Jordan)\b','',text,flags=re.I)
    if ADDITIONAL_FOREIGN.search(foreign_text) and not US.search(text_us):return 'additional_explicit_foreign_without_us'
    return ''

def screen_corpus():
    frame=pd.read_csv(DATA/'media_candidates.csv',keep_default_na=False)
    published=pd.to_datetime(frame.published_at,utc=True,errors='coerce')
    local=published.dt.tz_convert('America/New_York')
    next_midnight=(local.dt.tz_localize(None).dt.normalize()+pd.Timedelta(days=1)).dt.tz_localize('America/New_York').dt.tz_convert('UTC')
    frame['available_at']=next_midnight.astype(str)
    frame.loc[frame.source_group.eq('social'),'available_at']=published[frame.source_group.eq('social')].astype(str)
    if 'original_sampled' not in frame:frame['original_sampled']=frame.sampled
    frame['post_sample_exclusion_reason']=frame.text.map(strict_screen_reason)
    frame['sampled']=frame.original_sampled & frame.post_sample_exclusion_reason.eq('')
    frame.to_csv(DATA/'media_candidates.csv',index=False)
    corpus=frame[frame.sampled].sort_values(['month','source','id']).copy();corpus.to_csv(DATA/'media_corpus.csv',index=False)
    metadata=json.loads((OUT/'media_acquisition.json').read_text(encoding='utf-8'))
    removed=frame[frame.original_sampled & ~frame.sampled]
    removed[['id','source','month','text','post_sample_exclusion_reason']].to_csv(OUT/'media_relevance_exclusions.csv',index=False)
    metadata.update(sampled=len(corpus),pre_final_screen_sampled=int(frame.original_sampled.sum()),
       final_screen_removed=len(removed),final_screen_reasons=removed.post_sample_exclusion_reason.value_counts().to_dict(),
       corpus_sha256=sha(DATA/'media_corpus.csv'),
       final_screen_protocol='Deterministic conservative title-sense/country exclusions after maximum12/source/month draw; removed records are not replaced. Original300 annotation pool retained with eligibility flags.')
    write_json(OUT/'media_acquisition.json',metadata)
    key_path=ROOT/'data/annotations/sampling_key_KEEP_FROM_ANNOTATORS.csv'
    if key_path.exists():
        key=pd.read_csv(key_path);key['eligible_after_final_screen']=key.id.isin(corpus.id)
        key['final_exclusion_reason']=key.id.map(frame.drop_duplicates('id').set_index('id').post_sample_exclusion_reason).fillna('')
        key.to_csv(key_path,index=False)
    print(f'Final relevance screen removed {len(removed)} of {int(frame.original_sampled.sum())}; retained {len(corpus)} titles',flush=True)
    return corpus

